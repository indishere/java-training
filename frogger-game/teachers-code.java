    @Override
    public void keyPressed(KeyEvent e) {
        System.out.println(e.getKeyCode());
        int key = e.getKeyCode();
        if (key == 68 || key == 39) { //D or arrow right
            frogX = frogX + 10;
        }
        if (key == 65 || key == 37) { //A or arrow left
            frogX = frogX - 10;
        }
        if (key == 87 || key == 38) { //W or arrow Up
            frogY = frogY - 10;
        }
        if (key == 83 || key == 40) { //S or arrow Down
            frogY = frogY + 10;
        }

        repaint();
    }

