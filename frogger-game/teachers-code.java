    public boolean collide(int fx,int fy, int fw, int fh, int cx, int cy, int cw, int ch) {
        if (fx < cx+cw) { //left side of frog less than right side of car
            if (fx+fw > cx) {//frog right > car left
               if (fy < cy+ch) { //frog top < car bottom
                   if (fy + fh > cy) {//frog bottom > car top
                       System.out.println("Hit!!!!!");
                       return(true);
                   }
               }
            }
        }
        return(false);
    }

    class MyTimer extends Thread {
        public void run() {
            while(true) {
                carX = carX + 5;
                if (carX > 900) {
                    carX = -100;
                }
                car2X = car2X - 5;
                if (car2X < -100) {
                    car2X = 900;
                }

                boolean hit = false;
                boolean hit2 = false;
                hit = collide(frogX,frogY,50,50,carX,carY,100,50);
                hit2 = collide(frogX,frogY,50,50,car2X,car2Y,100,50);
                if (hit == true || hit2 == true) {
                    frogX = 375;
                    frogY = 525;
                }

                repaint();
                try {
                    sleep(20);
                } catch (Exception e) {
                    System.out.println("np");
                }
            }
        }
    }







